import fs from 'node:fs';
import path from 'node:path';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';

/**
 * Custom Vite PWA Plugin for DevShelf
 * 
 * Automatically captures all production bundle assets (HTML, JS chunks, CSS, icons)
 * and generates a production-ready Service Worker (dist/sw.js) with accurate precaching,
 * automatic cache invalidation, and zero hardcoded asset hashes.
 */
function devShelfPwaPlugin() {
  return {
    name: 'devshelf-pwa-plugin',
    apply: 'build', // Only executes during production build
    generateBundle(options, bundle) {
      const precacheAssets = [
        '/',
        '/index.html',
        '/manifest.webmanifest',
        '/favicon.svg',
        '/icons.svg',
        '/pwa-192x192.png',
        '/pwa-512x512.png',
        '/pwa-maskable-512x512.png',
        '/apple-touch-icon.png',
      ];

      // Add all output CSS, JS, and asset chunks generated by Vite
      for (const fileName of Object.keys(bundle)) {
        if (
          fileName.endsWith('.js') || 
          fileName.endsWith('.css') || 
          fileName.endsWith('.html') ||
          fileName.endsWith('.svg') ||
          fileName.endsWith('.png')
        ) {
          const url = '/' + fileName;
          if (!precacheAssets.includes(url)) {
            precacheAssets.push(url);
          }
        }
      }

      // Read sw.js template
      const swTemplatePath = path.resolve('src/sw.js');
      let swContent = fs.readFileSync(swTemplatePath, 'utf8');

      // Version name with timestamp for automated cache rotation
      const version = 'v1-' + Date.now();
      const cacheName = `devshelf-shell-${version}`;

      swContent = swContent
        .replace('__CACHE_NAME__', JSON.stringify(cacheName))
        .replace('__PRECACHE_ASSETS__', JSON.stringify(precacheAssets, null, 2));

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: swContent,
      });

      console.log(`[PWA Plugin] Generated dist/sw.js with ${precacheAssets.length} precached assets (${cacheName})`);
    },
  };
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    devShelfPwaPlugin(),
  ],
});
